"""Deployment snippets for a kept setup: Docker Compose, a systemd unit and Helm values.

They carry the engine, its flags and the model path as measured; nothing is deployed.
"""

from __future__ import annotations

import json
import os
import re
import shutil
from collections.abc import Sequence
from pathlib import Path
from typing import Literal

from . import __version__
from .engines import Engine
from .engines.llamacpp.command import known_build
from .runtime import RuntimeFailure

LLAMACPP_IMAGE = "ghcr.io/ggml-org/llama.cpp"


def render(
    fmt: Literal["compose", "systemd", "helm"],
    *,
    argv: Sequence[str],
    engine: Engine,
    version: str | None,
    model_path: Path,
    port: int,
    run: str | None = None,
    env: Sequence[str] = (),
) -> str:
    """The snippet in ``fmt`` for the engine command ``argv``, which serves ``model_path`` on
    ``port``, with the engine environment ``env`` (NAME=VALUE) of the kept setup.
    ``version`` is the engine version the setup was measured on."""
    origin = f"project run {run}" if run else "the project's current setup"
    header = f"# Generated by tensward {__version__} from {origin}; nothing was deployed."
    for word in (*argv, *env):
        if "\n" in word or "\r" in word or "\0" in word:
            raise RuntimeFailure(
                "a newline in an engine setting cannot go into a deployment snippet"
            )
    arguments = _container_arguments(engine, argv)
    image = _image(engine, version)
    nvidia = _nvidia(engine)
    if fmt == "systemd":
        return _systemd(header, argv, env)
    if fmt == "helm":
        return _helm(header, image, arguments, nvidia, port, env)
    return _compose(header, image, arguments, nvidia, model_path, port, env)


def _container_arguments(engine: Engine, argv: Sequence[str]) -> list[str]:
    """What follows the image's entrypoint: the engine command without its program (and, for
    vLLM, the ``serve`` word the image's entrypoint already holds)."""
    words = list(argv[1:])
    if engine.family == "vllm" and words[:1] == ["serve"]:
        words = words[1:]
    if "--host" not in words:
        words = [*words, "--host", "0.0.0.0"]
    return words


def _image(engine: Engine, version: str | None) -> str:
    """The image of the engine version the setup was measured on; with no run yet, vLLM's is the
    release this adapter is validated on, and llama.cpp's the build last probed."""
    if engine.family == "vllm":
        return f"vllm/vllm-openai:v{version}" if version else engine.default_image
    found = known_build()
    build = str(found[0].build) if found else version if version and version.isdigit() else None
    suffix = "server-cuda" if _nvidia(engine) else "server"
    return f"{LLAMACPP_IMAGE}:{suffix}-b{build}" if build else f"{LLAMACPP_IMAGE}:{suffix}"


def _nvidia(engine: Engine) -> bool:
    if engine.family == "vllm":
        return True
    found = known_build()
    return found is None or "CUDA" in found[0].backends


def _yaml(word: str) -> str:
    return json.dumps(word)


def _compose_scalar(word: str) -> str:
    return _yaml(word.replace("$", "$$"))


def _helm_scalar(word: str) -> str:
    return _yaml(word.replace("$(", "$$("))


_SYSTEMD_BARE = re.compile(r"[A-Za-z0-9_@+=:,./-]+")


def _systemd_word(word: str) -> str:
    if _SYSTEMD_BARE.fullmatch(word):
        return word
    escaped = word.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped.replace("$", "$$").replace("%", "%%") + '"'


def _systemd_environment(var: str) -> str:
    escaped = var.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped.replace("%", "%%") + '"'


def _systemd(header: str, argv: Sequence[str], env: Sequence[str]) -> str:
    program = argv[0] if os.path.isabs(argv[0]) else shutil.which(argv[0])
    if program is None:
        raise RuntimeFailure(
            f"{argv[0]} is not on this machine's PATH; a systemd unit needs its absolute path"
        )
    words = [program, *argv[1:]]
    if not any(word == "--host" or word.startswith("--host=") for word in words):
        words += ["--host", "127.0.0.1"]
    command = " ".join(_systemd_word(word) for word in words)
    return "\n".join(
        [
            header,
            "# Listens on this machine only, no API key: change --host and add one to expose it.",
            "[Unit]",
            "Description=Tensward-tuned inference server",
            "After=network-online.target",
            "Wants=network-online.target",
            "",
            "[Service]",
            *(f"Environment={_systemd_environment(var)}" for var in env),
            f"ExecStart={command}",
            "Restart=on-failure",
            "",
            "[Install]",
            "WantedBy=multi-user.target",
            "",
        ]
    )


def _compose(
    header: str,
    image: str,
    arguments: Sequence[str],
    nvidia: bool,
    model_path: Path,
    port: int,
    env: Sequence[str],
) -> str:
    lines = [
        header,
        "services:",
        "  inference:",
        f"    image: {image}",
        "    command:",
        *(f"      - {_compose_scalar(word)}" for word in arguments),
        "    ports:",
        f"      - {_compose_scalar(f'127.0.0.1:{port}:{port}')}",
        "    volumes:",
        f"      - {_compose_scalar(f'{model_path}:{model_path}:ro')}",
    ]
    if env:
        lines += ["    environment:", *(f"      - {_compose_scalar(var)}" for var in env)]
    if nvidia:
        lines += [
            "    deploy:",
            "      resources:",
            "        reservations:",
            "          devices:",
            "            - driver: nvidia",
            "              count: 1",
            "              capabilities: [gpu]",
        ]
    return "\n".join([*lines, ""])


def _helm(
    header: str,
    image: str,
    arguments: Sequence[str],
    nvidia: bool,
    port: int,
    env: Sequence[str],
) -> str:
    repository, _, tag = image.rpartition(":")
    lines = [
        header,
        "# The server has no API key: add one (vLLM: --api-key, llama.cpp: --api-key-file) before"
        " exposing the service.",
        "image:",
        f"  repository: {repository}",
        f'  tag: "{tag}"',
        "args:",
        *(f"  - {_helm_scalar(word)}" for word in arguments),
    ]
    if env:
        lines.append("env:")
        for var in env:
            name, _, value = var.partition("=")
            lines += [f"  - name: {_yaml(name)}", f"    value: {_helm_scalar(value)}"]
    if nvidia:
        lines += ["resources:", "  limits:", '    "nvidia.com/gpu": 1']
    lines += ["service:", f"  port: {port}"]
    return "\n".join([*lines, ""])
